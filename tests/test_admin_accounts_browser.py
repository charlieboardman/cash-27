import pytest
from test_browser_workflows import expect, answer_confirm


@pytest.mark.parametrize('width,language', [(1440, 'en'), (390, 'es')])
def test_admin_management_and_identity(web, width, language):
    page, post, artifacts = web
    page.context.set_extra_http_headers({})
    page.set_viewport_size({'width': width, 'height': 1000})
    page.goto('/settings')
    if language == 'es':
        page.get_by_role('button', name='Español', exact=True).click()
    rows = page.locator('#admin-list li')
    expect(rows).to_have_count(1)
    expect(rows.locator('[data-action="delete"]')).to_be_disabled()
    expect(rows.locator('[data-action="toggle"]')).to_be_disabled()
    form = page.locator('#admin-form')
    form.locator('[name="name"]').fill('Alex Example')
    form.locator('[name="password"]').fill('another-password')
    form.locator('[name="confirmation"]').fill('another-password')
    page.locator('#admin-save').click()
    expect(rows).to_have_count(2)
    second = rows.filter(has_text='Alex Example')
    second.locator('[data-action="edit"]').click()
    expect(form.locator('[name="password"]')).to_have_value('')
    form.locator('[name="name"]').fill('Alex Updated')
    page.locator('#admin-save').click()
    expect(rows).to_contain_text(['Test Admin', 'Alex Updated'])
    second = rows.filter(has_text='Alex Updated')
    second.locator('[data-action="toggle"]').click()
    expect(second).to_contain_text('Inactivo' if language == 'es' else 'Disabled')
    expect(rows.first.locator('[data-action="delete"]')).to_be_disabled()
    second.locator('[data-action="toggle"]').click()
    expect(second).to_contain_text('Activo' if language == 'es' else 'Enabled')
    assert page.evaluate('[...cashI18n.missing]') == []
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.locator('#admin-accounts').screenshot(path=str(artifacts / f'admins-{language}.png'))
    page.goto('/api/logout')
    page.locator('[name="password"]').fill('another-password')
    page.locator('#login button[type="submit"]').click()
    page.wait_for_url('**/overview')
    expect(page.locator('#signed-in-admin')).to_have_text('Alex Updated')
    page.goto('/transactions/new')
    expect(page.locator('[name="approver_name"]')).to_have_value('Alex Updated')
    page.goto('/settings')
    rows = page.locator('#admin-list li')
    rows.filter(has_text='Test Admin').locator('[data-action="delete"]').click()
    expect(page.locator('dialog.confirm-dialog button[value="cancel"]')).to_have_text("Cancelar" if language == "es" else "Cancel")
    answer_confirm(page)
    expect(rows).to_have_count(1)
    expect(rows.locator('[data-action="delete"]')).to_be_disabled()

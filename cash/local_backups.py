"""Scheduled, verified local recovery archives; no external transport."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import fcntl
import json
import os
from pathlib import Path
import re
import signal
import tempfile
import time

from .ops import backup_archive, verify_archive


KINDS = {"scheduled": 7, "pre-upgrade": 3, "manual": 3}
ARCHIVE_NAME = re.compile(r"cash-27-full-\d{8}T\d{12}Z\.tar\.gz")


def log(state: str, **details) -> None:
    print(json.dumps({"at": datetime.now(timezone.utc).isoformat(),
                      "state": state, **details}), flush=True)


def create_local_archive(data_root: Path, *, kind: str = "manual",
                         keep: int | None = None) -> dict:
    """Publish only verified archives, then rotate this job's own files.

    One filesystem lock serializes scheduled and pre-upgrade runs. Other
    recovery material (database-import safety copies, manually saved files,
    and pre-restore archives) is never included in automatic retention.
    """
    if kind not in KINDS:
        raise ValueError("unknown local archive kind")
    keep = KINDS[kind] if keep is None else keep
    if keep < 1:
        raise ValueError("keep must be positive")
    root = Path(data_root) / "backups" / "local"
    root.mkdir(parents=True, exist_ok=True, mode=0o700)
    with (root / ".lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        destination = root / kind
        destination.mkdir(exist_ok=True, mode=0o700)
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        name = f"cash-27-full-{stamp}.tar.gz"
        target = destination / name
        log("running", kind=kind, archive=name)
        # All temporary archive and verification files stay on the data disk,
        # not the container's small /tmp tmpfs. No completed file appears until
        # the archive has passed a staged restore, hashes, and ledger replay.
        with tempfile.TemporaryDirectory(prefix=".building-", dir=root) as work:
            pending = Path(work) / name
            result = backup_archive(data_root, pending)
            verification = verify_archive(pending)
            with pending.open("rb") as archive:
                os.fsync(archive.fileno())
            os.replace(pending, target)
        # Count-based retention is scoped to names generated by this service.
        archives = sorted(path for path in destination.iterdir()
                          if ARCHIVE_NAME.fullmatch(path.name)
                          and path.is_file() and not path.is_symlink())
        # Always protect the file just made, even if the host clock moved back.
        previous = [path for path in archives if path != target]
        removed = previous[:max(0, len(previous) - (keep - 1))]
        for path in removed:
            path.unlink()
        result = {"archive": str(target), "kind": kind,
                  "size_bytes": result["size_bytes"],
                  "sha256": result["sha256"],
                  "integrity": verification["integrity"],
                  "removed": [path.name for path in removed]}
        log("success", **result)
        return result


def positive_environment(name: str, default: int) -> int:
    try:
        value = int(os.environ.get(name, str(default)))
    except ValueError as exc:
        raise ValueError(f"{name} must be a positive integer") from exc
    if value < 1:
        raise ValueError(f"{name} must be a positive integer")
    return value


def run_loop(data_root: Path, *, interval: int, retry: int, keep: int) -> None:
    while True:
        try:
            create_local_archive(data_root, kind="scheduled", keep=keep)
        except (Exception, SystemExit) as exc:
            if isinstance(exc, SystemExit) and exc.code in (None, 0):
                raise
            # Includes first boot before the app initializes its database.
            # Keep all previous archives and retry without restarting Flask.
            log("failure", kind="scheduled", message=str(exc), retry_seconds=retry)
            delay = retry
        else:
            delay = interval
        time.sleep(delay)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("once", "loop", "health"))
    parser.add_argument("--kind", choices=KINDS, default="manual")
    args = parser.parse_args()
    os.umask(0o077)

    def stop(*_):
        raise SystemExit(0)

    signal.signal(signal.SIGTERM, stop)
    data_root = Path(os.environ.get("CASH_DATA_ROOT", "/data"))
    interval = positive_environment("CASH_LOCAL_BACKUP_INTERVAL_SECONDS", 86400)
    retry = positive_environment("CASH_LOCAL_BACKUP_RETRY_SECONDS", 900)
    if args.action == "health":
        # This checks local archives only; it cannot attest to VM backups.
        folder = data_root / "backups" / "local" / "scheduled"
        latest = max((path.stat().st_mtime for path in folder.glob("*.tar.gz")
                      if ARCHIVE_NAME.fullmatch(path.name)
                      and path.is_file() and not path.is_symlink()), default=0)
        raise SystemExit(0 if latest and time.time() - latest <=
                         interval + max(3600, 2 * retry) else 1)
    kind = "scheduled" if args.action == "loop" else args.kind
    variable = {"scheduled": "CASH_LOCAL_BACKUP_KEEP",
                "pre-upgrade": "CASH_LOCAL_BACKUP_UPGRADE_KEEP",
                "manual": "CASH_LOCAL_BACKUP_MANUAL_KEEP"}[kind]
    keep = positive_environment(variable, KINDS[kind])
    if args.action == "loop":
        run_loop(data_root, interval=interval, retry=retry, keep=keep)
    else:
        create_local_archive(data_root, kind=kind, keep=keep)


if __name__ == "__main__":
    main()
